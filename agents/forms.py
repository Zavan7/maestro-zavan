"""Formulários do app de agentes.

English:
    Forms for the agents app.
"""

from django import forms

from agents.models import Agente


class AgenteForm(forms.ModelForm):
    """Cadastro de agente: só o nome; o token é gerado pelo serviço.

    English:
        Agent sign-up: only the name; the token is generated by the
        service.
    """

    class Meta:
        """Só o nome, com rótulo e dica curtos.

        English:
            Only the name, with a short label and hint.
        """

        model = Agente
        fields = ["nome"]
        labels = {"nome": "nome do agente"}
        widgets = {
            "nome": forms.TextInput(attrs={"placeholder": "servidor-zv-01"})
        }
